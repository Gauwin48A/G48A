#!/usr/bin/env node

const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");

const ROOT_DIR = path.resolve(__dirname, "../../..");
const OUTPUT_PATH = path.join(ROOT_DIR, "server", "docs", "project", "CHANGELOG_AUTO.md");
const DEFAULT_LIMIT = 200;

const TYPE_LABELS = {
  feat: "Features",
  fix: "Fixes",
  perf: "Performance",
  refactor: "Refactors",
  docs: "Documentation",
  test: "Tests",
  chore: "Chores",
  ci: "CI",
  build: "Build",
  security: "Security",
  other: "Other",
};

function parseLimit(raw) {
  const parsed = Number.parseInt(String(raw || ""), 10);
  if (!Number.isFinite(parsed) || parsed < 20) return DEFAULT_LIMIT;
  return Math.min(parsed, 1000);
}

function normalizeType(message) {
  const match = String(message || "").match(
    /^(feat|fix|perf|refactor|docs|test|chore|ci|build|security)(\(.+\))?:/i,
  );
  return match ? match[1].toLowerCase() : "other";
}

function readGitLog(limit) {
  const result = spawnSync(
    "git",
    ["log", "-n", String(limit), "--date=short", "--pretty=format:%h|%ad|%s"],
    {
      cwd: ROOT_DIR,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    },
  );

  if (result.error) {
    throw result.error;
  }
  if (result.status !== 0) {
    throw new Error(result.stderr || "git log failed");
  }

  const raw = result.stdout;

  return raw
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => {
      const [hash, date, ...messageParts] = line.split("|");
      const message = messageParts.join("|").trim();
      return {
        hash: hash?.trim(),
        date: date?.trim(),
        message,
        type: normalizeType(message),
      };
    })
    .filter((entry) => entry.hash && entry.date && entry.message);
}

function renderMarkdown(entries, limit) {
  const generatedAt = new Date().toISOString();
  const grouped = new Map();
  Object.keys(TYPE_LABELS).forEach((type) => grouped.set(type, []));

  for (const entry of entries) {
    const bucket = grouped.get(entry.type) || grouped.get("other");
    bucket.push(entry);
  }

  const lines = [];
  lines.push("# Auto Changelog");
  lines.push("");
  lines.push(`Generated: ${generatedAt}`);
  lines.push(`Commit window: last ${limit} commits`);
  lines.push("");
  lines.push(
    "> This file is generated by `npm run changelog:generate`. Do not edit manually.",
  );
  lines.push("");

  for (const [type, label] of Object.entries(TYPE_LABELS)) {
    const bucket = grouped.get(type) || [];
    if (!bucket.length) continue;

    lines.push(`## ${label}`);
    lines.push("");
    for (const item of bucket) {
      lines.push(`- ${item.date} \`${item.hash}\` ${item.message}`);
    }
    lines.push("");
  }

  return `${lines.join("\n").trim()}\n`;
}

function main() {
  const limit = parseLimit(process.env.CHANGELOG_LIMIT);
  let entries = [];

  try {
    entries = readGitLog(limit);
  } catch (error) {
    console.error("[changelog] Failed to read git history.");
    console.error(error.message);
    process.exitCode = 1;
    return;
  }

  if (!entries.length) {
    console.warn("[changelog] No commits found. Skipping output.");
    return;
  }

  const markdown = renderMarkdown(entries, limit);
  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, markdown, "utf8");
  console.log(`[changelog] generated: ${path.relative(ROOT_DIR, OUTPUT_PATH)}`);
}

main();


