import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { loadFirebaseEnv } from './firebase-config.mjs';

const args = process.argv.slice(2);

const getArgValue = (flag) => {
  const direct = args.find((value) => value.startsWith(`${flag}=`));
  if (direct) {
    return direct.slice(flag.length + 1);
  }
  const index = args.findIndex((value) => value === flag);
  if (index >= 0) {
    return args[index + 1];
  }
  return null;
};

const mode = getArgValue('--mode') || process.env.NODE_ENV || 'development';
const shouldWriteSw = args.includes('--write-sw');

const { config, missingKeys, configured } = loadFirebaseEnv({ mode, root: process.cwd() });

if (!configured) {
  const uniqueMissing = Array.from(new Set(missingKeys));
  console.warn(
    `[firebase-preflight] Missing or placeholder Firebase envs (${mode}): ${uniqueMissing.join(', ')}`
  );
} else {
  console.log(`[firebase-preflight] Firebase env looks configured for ${mode}.`);
}

if (shouldWriteSw) {
  const publicDir = resolve(process.cwd(), 'public');
  const swPath = resolve(publicDir, 'firebase-messaging-sw.js');
  mkdirSync(publicDir, { recursive: true });

  const swContent = `/**
 * Firebase Messaging Service Worker
 *
 * AUTO-GENERATED by scripts/firebase-preflight.mjs
 * Do not edit this file directly.
 */

const firebaseConfig = ${JSON.stringify(config, null, 4)};

const PLACEHOLDER_MARKERS = ${JSON.stringify([
    'YOUR_API_KEY',
    'YOUR_PROJECT_ID',
    'YOUR_SENDER_ID',
    'YOUR_APP_ID',
    'YOUR_VAPID_KEY'
  ])};

const isPlaceholder = (value) => {
  if (!value) return true;
  return PLACEHOLDER_MARKERS.some((marker) => String(value).includes(marker));
};

const isConfigured = Object.values(firebaseConfig).every((value) => !isPlaceholder(value));

if (!isConfigured) {
  console.log('[FCM SW] Firebase not configured - push notifications disabled');
} else {
  importScripts('https://www.gstatic.com/firebasejs/10.7.1/firebase-app-compat.js');
  importScripts('https://www.gstatic.com/firebasejs/10.7.1/firebase-messaging-compat.js');

  firebase.initializeApp(firebaseConfig);
  const messaging = firebase.messaging();

  messaging.onBackgroundMessage((payload) => {
    console.log('[FCM SW] Background message received:', payload);

    const notificationTitle = payload.notification?.title || 'Mhub Notification';
    const notificationOptions = {
      body: payload.notification?.body || 'You have a new notification',
      icon: '/favicon.ico',
      badge: '/favicon.ico',
      tag: payload.data?.tag || 'mhub-notification',
      data: payload.data,
      actions: [
        { action: 'open', title: 'Open' },
        { action: 'dismiss', title: 'Dismiss' }
      ]
    };

    self.registration.showNotification(notificationTitle, notificationOptions);
  });

  self.addEventListener('notificationclick', (event) => {
    console.log('[FCM SW] Notification clicked:', event);
    event.notification.close();

    if (event.action === 'dismiss') return;

    event.waitUntil(
      clients.matchAll({ type: 'window', includeUncontrolled: true })
        .then((clientList) => {
          for (const client of clientList) {
            if (client.url.includes(self.location.origin) && 'focus' in client) {
              return client.focus();
            }
          }
          if (clients.openWindow) {
            const targetUrl = event.notification.data?.url || '/notifications';
            return clients.openWindow(targetUrl);
          }
        })
    );
  });
}

self.addEventListener('install', () => {
  console.log('[FCM SW] Service Worker installed');
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  console.log('[FCM SW] Service Worker activated');
  event.waitUntil(clients.claim());
});
`;

  writeFileSync(swPath, swContent, 'utf8');
  console.log(`[firebase-preflight] Wrote ${swPath}`);
}
